const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {chromium}=require('playwright');
const PDFLib=require('pdf-lib');
const {createServer}=require('../pdfjs/server.cjs');

(async()=>{
 const server=createServer();await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const folder=fs.mkdtempSync(path.join(os.tmpdir(),'fbar-pdf-save-'));
 try{
  const errors=[],origin=`http://127.0.0.1:${server.address().port}`;
  const open=async()=>{const page=await browser.newPage();page.on('pageerror',error=>errors.push(error.message));await page.goto(origin);await page.waitForFunction(()=>window.experiment);return page;};
  const page=await open();await page.evaluate(()=>experiment.generate(3));
  assert.equal(await page.locator('#resume-file').count(),0);
  assert.equal(await page.locator('#save-work').textContent(),'Save PDF');
  await page.locator('#add-institution').click();
  await page.getByLabel('Institution name 4',{exact:true}).fill('UNUSED BANK');
  await page.locator('#add-owner').click();
  await page.getByLabel('Owner 1 Last name or organization name',{exact:true}).fill('UNUSED OWNER');
  await page.getByLabel('First name',{exact:true}).fill('');
  await page.getByLabel('Maximum USD 1',{exact:true}).fill('MISSING');
  const expected=await page.evaluate(async()=>{const data=await import('/pdfjs/data-model.mjs');return data.serialize(experiment.getModel());});
  await page.locator('#draft').click();await page.waitForFunction(()=>!document.querySelector('#editor').inert);
  assert(await page.locator('#issues').isVisible());
  const download=page.waitForEvent('download');await page.locator('#save-work').click();
  assert.equal(await page.locator('#action-dialog').isVisible(),false);
  const file=path.join(folder,'work.pdf');await (await download).saveAs(file);
  assert.equal(fs.readFileSync(file).subarray(0,5).toString(),'%PDF-');
  const withState=await PDFLib.PDFDocument.load(fs.readFileSync(file));
  assert(withState.catalog.get(PDFLib.PDFName.of('FBARWorkState')));
  const resumed=await open();await resumed.locator('#import-file').setInputFiles(file);
  await resumed.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Saved PDF reopened'));
  assert.equal(await resumed.getByLabel('Maximum USD 1',{exact:true}).inputValue(),'MISSING');
  assert.equal(await resumed.getByLabel('Institution name 4',{exact:true}).inputValue(),'UNUSED BANK');
  assert.equal(await resumed.getByLabel('Owner 1 Last name or organization name',{exact:true}).inputValue(),'UNUSED OWNER');
  assert.equal(await resumed.evaluate(async()=>{const data=await import('/pdfjs/data-model.mjs');return data.serialize(experiment.getModel());}),expected);
  assert.match(await resumed.locator('#work-summary').textContent(),/PDF reopened/);
  const legacy=await require('./read-saved-pdf-work.cjs')(file),legacyFile=path.join(folder,'older-work.json');
  fs.writeFileSync(legacyFile,JSON.stringify(legacy));
  const older=await open();await older.locator('#import-file').setInputFiles(legacyFile);
  await older.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Saved work resumed'));
  assert.equal(await older.evaluate(async()=>{const data=await import('/pdfjs/data-model.mjs');return data.serialize(experiment.getModel());}),expected);
  const altered=fs.readFileSync(file),position=altered.indexOf('MISSING');
  assert(position>=0);altered.write('CHANGED',position,'ascii');
  const alteredFile=path.join(folder,'altered.pdf');fs.writeFileSync(alteredFile,altered);
  await resumed.getByLabel('Maximum USD 1',{exact:true}).fill('10001');
  const before=await resumed.evaluate(async()=>{const data=await import('/pdfjs/data-model.mjs');return data.serialize(experiment.getModel());});
  await resumed.locator('#import-file').setInputFiles(alteredFile);
  await resumed.waitForFunction(()=>document.querySelector('#status').textContent.includes('Saved PDF details do not match'));
  assert.equal(await resumed.evaluate(async()=>{const data=await import('/pdfjs/data-model.mjs');return data.serialize(experiment.getModel());}),before);
  const ordinary=await open();await ordinary.evaluate(()=>experiment.generate(1));
  const checked=await ordinary.evaluate(async()=>Array.from(await experiment.buildDraft()));
  assert.equal((await PDFLib.PDFDocument.load(Uint8Array.from(checked))).catalog.get(PDFLib.PDFName.of('FBARWorkState')),undefined);
  const plainDraft=await open();await plainDraft.locator('#new').click();
  await plainDraft.waitForFunction(()=>!document.querySelector('#editor').hidden);
  await plainDraft.locator('#filer-fields').getByLabel('Country code',{exact:true}).fill(' INVALID ');
  const ordinaryXml=await plainDraft.evaluate(async()=>{const data=await import('/pdfjs/data-model.mjs');return data.serialize(experiment.getModel());});
  const ordinaryDownload=plainDraft.waitForEvent('download');await plainDraft.locator('#save-work').click();
  assert.equal(await plainDraft.locator('#action-dialog').isVisible(),false);
  const ordinaryFile=path.join(folder,'ordinary.pdf');await (await ordinaryDownload).saveAs(ordinaryFile);
  assert.equal((await PDFLib.PDFDocument.load(fs.readFileSync(ordinaryFile))).catalog.get(PDFLib.PDFName.of('FBARWorkState')),undefined);
  const ordinaryReopened=await open();await ordinaryReopened.locator('#import-file').setInputFiles(ordinaryFile);
  await ordinaryReopened.waitForFunction(()=>!document.querySelector('#editor').hidden&&!document.querySelector('#editor').inert);
  assert.equal(await ordinaryReopened.evaluate(async()=>{const data=await import('/pdfjs/data-model.mjs');return data.serialize(experiment.getModel());}),ordinaryXml);
  await plainDraft.locator('#add-institution').click();
  await plainDraft.getByLabel('Institution name 1',{exact:true}).fill('UNUSED BANK');
  const exceptionalDownload=plainDraft.waitForEvent('download');await plainDraft.locator('#save-work').click();
  assert.equal(await plainDraft.locator('#action-dialog').isVisible(),false);
  const exceptionalFile=path.join(folder,'exceptional.pdf');await (await exceptionalDownload).saveAs(exceptionalFile);
  assert((await PDFLib.PDFDocument.load(fs.readFileSync(exceptionalFile))).catalog.get(PDFLib.PDFName.of('FBARWorkState')));
  const exceptionalReopened=await open();await exceptionalReopened.locator('#import-file').setInputFiles(exceptionalFile);
  await exceptionalReopened.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Saved PDF reopened'));
  assert.equal(await exceptionalReopened.getByLabel('Institution name 1',{exact:true}).inputValue(),'UNUSED BANK');
  assert.deepEqual(errors,[]);
  console.log('PASS: ordinary and checked PDFs have no extra catalog entry; shared rows, incomplete values, older work and changed-PDF rejection work');
 }finally{await browser.close();await new Promise(resolve=>server.close(resolve));fs.rmSync(folder,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
